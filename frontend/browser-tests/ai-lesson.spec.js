  await page.route('**/api/ai/chat', async (route) => {
    requests.push(route.request().postDataJSON())
    await route.fulfill({ json: { reply: 'I can clarify the instructions for this part.' } })
  })
  await page.goto('./#/ai-lesson')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await expect(page.locator('.brand')).toContainText('DYNAMIC LEARNING')
  await expect(page.getByRole('button', { name: 'Submit pre-test & continue' })).toBeDisabled()
  await expect(page.locator('#lesson-tutor')).toHaveCount(0)
  await expect(page.locator('#tutor-message')).toHaveCount(0)
  await expect(page.locator('.mobile-tutor-toggle')).toHaveCount(0)
  expect(requests).toEqual([])
  await pretest(page)
  await expect(page.getByRole('button', { name: /Pre-test$/ })).toBeDisabled()
  await page.getByRole('button', { name: 'Next animation step' }).click()
  await expect(page.getByText('Call stack · 2 frames', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('introduction-desktop.png'), fullPage: true })
  await page.locator('#doll-explanation').fill('The solid doll is the base case. Smaller dolls make progress toward it.')
  await page.getByRole('button', { name: 'Start the conversation' }).click()
  await expect(page.getByText('I can clarify the instructions for this part.')).toBeVisible()
  expect(requests[0].step_id).toBe('ai-introduction')
  expect(JSON.parse(requests[0].learner_context).baseline.score).toBe(4)
  await page.reload()
  await expect(page.locator('#doll-explanation')).toHaveValue(/solid doll/)
  await page.getByRole('button', { name: 'Save & continue' }).click()

  await page.getByRole('radio', { name: /Fibonacci numbers/ }).check()
  await page.locator('#suitability-reason').fill('It branches into the two preceding inputs.')
  await page.locator('#fib-recurrence').fill('F(0)=0, F(1)=1; F(n)=F(n-1)+F(n-2).')
  await page.locator('#code-fibonacci').fill(fib)
  await page.getByRole('button', { name: 'Ask for a first hint', exact: true }).click()
  await expect(page.getByText('I can clarify the instructions for this part.')).toBeVisible()
  expect(requests.at(-1).step_id).toBe('ai-practice')
  expect(JSON.parse(requests.at(-1).learner_context).code).toContain('def fib(n):')
