  await page.getByRole('button', { name: 'Run tests', exact: true }).click()
  await expect(page.getByText('All practice checks passed.', { exact: true })).toBeVisible({ timeout: 70000 })
  await page.locator('#fib-prediction').fill('3')
  await page.locator('#stack-prediction').fill('4')
  await page.getByRole('button', { name: 'Explore the call tree' }).click()
  await page.getByRole('button', { name: 'Highlight fib(2) calls' }).first().click()
  await expect(page.getByText('Highlighted: fib(2). 2 calls in this tree.', { exact: true })).toBeVisible()
  await page.locator('#trace-explanation').fill('The root waits for both smaller calls before returning their sum.')
  await page.getByRole('button', { name: 'Save & continue' }).click()

  await page.locator('#repeated-count').fill('2')
  await page.locator('#redundancy-explanation').fill('Identical inputs return the same result.')
  await page.locator('#code-memoization').fill(fib.replaceAll('fib(', 'fib_memo('))
  await page.getByRole('button', { name: 'Run tests', exact: true }).click()
  await expect(page.getByText('There is still repeated work to investigate.', { exact: false })).toBeVisible({ timeout: 70000 })
  await page.locator('#code-memoization').fill(memo)
  await page.getByRole('button', { name: 'Run tests', exact: true }).click()
  await expect(page.getByText('All practice checks passed.', { exact: true })).toBeVisible({ timeout: 15000 })
  await page.getByRole('button', { name: 'Compare with a memoized trace' }).click()
  await expect(page.getByText('Calls that reuse a saved result')).toBeVisible()
  await page.locator('#complexity-explanation').fill('Each distinct input is computed once: O(n) time and O(n) memory.')
  await page.getByRole('button', { name: 'Start the transfer task' }).click()
  await expect(page.getByRole('button', { name: /Build & trace$/ })).toBeDisabled()
  await expect(page.getByRole('button', { name: /Optimize$/ })).toBeDisabled()
  await expect(page.locator('#lesson-tutor')).toHaveCount(0)
  await expect(page.locator('#tutor-message')).toHaveCount(0)
  await expect(page.locator('.mobile-tutor-toggle')).toHaveCount(0)

