import { test, expect } from '@playwright/test'

const fib = 'def fib(n):\n    if n < 2:\n        return n\n    return fib(n - 1) + fib(n - 2)\n'
const memo = 'def fib_memo(n):\n    cache = {}\n    def solve(k):\n        if k in cache:\n            return cache[k]\n        cache[k] = k if k < 2 else solve(k - 1) + solve(k - 2)\n        return cache[k]\n    return solve(n)\n'
const stairs = 'def climb_stairs(n):\n    cache = {}\n    def solve(k):\n        if k in cache:\n            return cache[k]\n        cache[k] = 1 if k < 2 else solve(k - 1) + solve(k - 2)\n        return cache[k]\n    return solve(n)\n\nprint(climb_stairs(4))\n'

async function pretest(page) {
  for (const [name, value] of [['self-similar', 0], ['termination', 1], ['trace-baseline', 1], ['cache-baseline', 1]]) await page.locator(`input[name="${name}"][value="${value}"]`).check()
  await page.getByRole('button', { name: 'Submit pre-test & continue' }).click()
}

